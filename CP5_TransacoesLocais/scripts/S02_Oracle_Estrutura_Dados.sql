-- Oracle 12c ou superior. Execute no schema próprio do CP5, nunca SYS/SYSTEM.
-- Criação inicial: se já existirem tabelas, use S04 para reinicializar os dados.
-- DDL no Oracle confirma implicitamente a transação: não execute durante testes.
CREATE TABLE CLIENTE (
    Id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nome VARCHAR2(100) NOT NULL,
    Documento VARCHAR2(20) NOT NULL,
    Ativo NUMBER(1) DEFAULT 1 NOT NULL CHECK (Ativo IN (0, 1))
);
CREATE TABLE TIPO_CONTA (
    Id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Descricao VARCHAR2(50) NOT NULL
);
CREATE TABLE CONTA (
    Id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ClienteId NUMBER(10) NOT NULL REFERENCES CLIENTE(Id),
    TipoContaId NUMBER(10) NOT NULL REFERENCES TIPO_CONTA(Id),
    Numero VARCHAR2(20) NOT NULL UNIQUE,
    Saldo NUMBER(18,2) NOT NULL CHECK (Saldo >= 0),
    Ativa NUMBER(1) DEFAULT 1 NOT NULL CHECK (Ativa IN (0, 1))
);
CREATE TABLE TRANSFERENCIA (
    Id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ContaOrigemId NUMBER(10) NOT NULL REFERENCES CONTA(Id),
    ContaDestinoId NUMBER(10) NOT NULL REFERENCES CONTA(Id),
    Valor NUMBER(18,2) NOT NULL CHECK (Valor > 0),
    DataTransferencia TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    Observacao VARCHAR2(255),
    CHECK (ContaOrigemId <> ContaDestinoId)
);
